#!/bin/sh
# Regenerates disposable-domains.js from the community blocklist
# (github.com/disposable-email-domains/disposable-email-domains). Bundled, not fetched
# at request time, so no third-party service sits in the validation path. Redeploy after.
set -e
cd "$(dirname "$0")"
curl -fsSL https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf \
  | grep -E '^[a-z0-9.-]+$' \
  | awk -v d="$(date +%Y-%m-%d)" '
      BEGIN { printf "// GENERATED by gen-disposable.sh on %s - do not edit by hand.\nexport const DISPOSABLE = new Set(\"", d }
      { printf "%s%s", (NR > 1 ? " " : ""), $0 }
      END { print "\".split(\" \"));" }' \
  > disposable-domains.js
echo "wrote $(wc -c < disposable-domains.js) bytes"
